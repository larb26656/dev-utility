export function hasSuggestions(level: SatirLevel): boolean {
  const set = SATIR_SUGGESTIONS[level]
  return set.groups.length > 0 || (set.prompts?.length ?? 0) > 0
}

export function appendSuggestion(current: string, addition: string): string {
  const trimmed = current.trimEnd()
  return trimmed.length === 0 ? addition : `${trimmed}\n${addition}`
}